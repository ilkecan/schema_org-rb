require "active_support/concern"

module SchemaOrg
  module Mixins
    module Service
      extend ActiveSupport::Concern

      include Intangible

      included do
        option :aggregate_rating # The overall rating, based on a collection of reviews or ratings, of the item.
        option :available_channel # A means of accessing the service (e.g. a phone bank, a web site, a location, etc.).
        option :brand # The brand(s) associated with a product or service, or the brand(s) maintained by an organization or business person.
        option :category # A category for the item. Greater signs or slashes can be used to informally indicate a category hierarchy.
        option :has_offer_catalog # Indicates an OfferCatalog listing for this Organization, Person, or Service.
        option :hours_available # The hours during which this service or contact is available.
        option :is_related_to # A pointer to another, somehow related product (or multiple products).
        option :is_similar_to # A pointer to another, functionally similar product (or multiple products).
        option :logo # An associated logo.
        option :produces # The tangible thing generated by the service, e.g. a passport, permit, etc. Superseded by `service_output`.
        option :provider_mobility # Indicates the mobility of a provided service (e.g. 'static', 'dynamic').
        option :service_audience # The audience eligible for this service. Superseded by `audience`.
        option :service_type # The type of service being offered, e.g. veterans' benefits, emergency relief, etc.
        option :slogan # A slogan or motto associated with the item.
        option :audience # An intended audience, i.e. a group for whom something was created. Supersedes `service_audience`.
        option :award # An award won by or for this item. Supersedes `awards`.
        option :broker # An entity that arranges for an exchange between a buyer and a seller.  In most cases a broker never acquires or releases ownership of a product or service involved in an exchange.  If it is not clear whether an entity is a broker, seller, or buyer, the latter two terms are preferred. Supersedes `booking_agent`.
        option :offers # An offer to provide this item&#x2014;for example, an offer to sell a product, rent the DVD of a movie, perform a service, or give away tickets to an event. Use [[businessFunction]] to indicate the kind of transaction offered, i.e. sell, lease, etc. This property can also be used to describe a [[Demand]]. While this property is listed as expected on a number of common types, it can be used in others. In that case, using a second type, such as Product or a subtype of Product, can clarify the nature of the offer. Inverse-property: `item_offered`.
        option :provider # The service provider, service operator, or service performer; the goods producer. Another party (a seller) may offer those services or goods on behalf of the provider. A provider may also serve as the seller. Supersedes `carrier`.
        option :review # A review of the item. Supersedes `reviews`.
        option :service_area # The geographic area where the service is provided. Supersedes `area`. Superseded by `area_served`.
        option :service_output # The tangible thing generated by the service, e.g. a passport, permit, etc. Supersedes `produces`.
        option :area_served # The geographic area where a service or offered item is provided. Supersedes `service_area`.
      end
    end
  end
end
